"""Standalone reproducer rendering, requested by the engine's `reproducer` method.

The engine minimized a finding and confirmed the minimized input reproduces; it then asks
the plugin — which owns the target language — to render the call. The engine stores the
returned bytes verbatim under the extension named here. Nothing in this module imports or
executes the target: rendering is string work, so it never needs the invocation deadline.

The script mirrors `materialize.py`'s semantics: an `object` becomes a `SimpleNamespace`
(both attribute access and `vars()` work, as with the harness's `_Obj`), a `function`
becomes the same stub behavior the harness built, and a `stream` becomes an iterator. A
method's receiver is constructed with no arguments, which is exactly what this harness's
constructible rule means for a class.
"""

import json

SPECIAL_NUMBERS = {"naN": "float('nan')", "infinity": "float('inf')", "negativeInfinity": "float('-inf')"}


def render(target_id, file, name, class_name, values):
    """Return the `reproducer` response for one minimized call."""
    helpers = {"throw": False, "capture": False, "opaque": []}
    args = [literal(value, 0, helpers) for value in values]
    out = [
        f"# autofuzz reproducer for {target_id}",
        "# Generated by the python harness at the engine's request; the arguments are the",
        "# finding's minimized input. Run it with Python 3 from anywhere:",
        "#   python3 <this file>",
        "# A deadline finding reproduces by not returning: stop this script once the",
        "# finding's deadline has elapsed. The wall clock is the fault.",
        "import importlib.util",
        "import types",
        "",
        f'_spec = importlib.util.spec_from_file_location("afz_repro", {json.dumps(file)})',
        "_module = importlib.util.module_from_spec(_spec)",
        "_spec.loader.exec_module(_module)",
        "",
    ]
    if class_name is not None:
        method = name.split(".", 1)[-1]
        out.append("# The receiver is constructed with no arguments: discovery only fuzzes a")
        out.append("# method whose constructor the harness could build.")
        callee = f"_module.{class_name}().{method}"
    else:
        callee = f"_module.{name}"
    if helpers["throw"]:
        out += ["", "def _afz_stub_throw(*_args, **_kwargs):", '    raise RuntimeError("afz: stub called")']
    if helpers["capture"]:
        out += ["", "_afz_stub_captured = []", "", "def _afz_stub_capture(*args, **kwargs):", "    _afz_stub_captured.append((args, kwargs))"]
    for ty in helpers["opaque"]:
        out.append(f"# An opaque {ty} is passed as None: a fixture is needed to build the real value.")
    out += ["", f"{callee}({', '.join(args)})", ""]
    return {"extension": "py", "script": "\n".join(out)}


def literal(value, depth, helpers):
    """Python source for one `ValueTree`. Every tag `materialize.py` accepts has a case,
    because a reproducer that quietly drops or alters an argument calls the target with
    something the finding never used."""
    pad = "    " * (depth + 1)
    close_pad = "    " * depth
    tag = value["node"]
    if tag in ("null", "undefined"):
        return "None"
    if tag == "boolean":
        return "True" if value["value"] else "False"
    if tag == "number":
        raw = value["value"]
        if isinstance(raw, str):
            return SPECIAL_NUMBERS[raw]
        if isinstance(raw, bool):
            return "1.0" if raw else "0.0"
        rendered = repr(float(raw))
        return rendered
    if tag == "bigInt":
        return str(int(value["value"]))
    if tag == "string":
        return json.dumps(value["value"])
    if tag == "literal":
        return json_to_py(value["value"], depth, helpers)
    if tag == "array":
        return collection(value.get("items", []), "[", "]", depth, pad, close_pad, helpers)
    if tag == "tuple":
        items = value.get("items", [])
        if len(items) == 1:
            # A one-element tuple needs the trailing comma or it is a parenthesized value.
            return f"({literal(items[0], depth, helpers)},)"
        return collection(items, "(", ")", depth, pad, close_pad, helpers)
    if tag == "set":
        items = value.get("items", [])
        if not items:
            return "set()"
        return collection(items, "{", "}", depth, pad, close_pad, helpers)
    if tag == "map":
        entries = value.get("entries", [])
        if not entries:
            return "{}"
        pairs = [f"{pad}{literal(k, depth + 1, helpers)}: {literal(v, depth + 1, helpers)}" for k, v in entries]
        return "{\n" + ",\n".join(pairs) + f"\n{close_pad}}}"
    if tag == "object":
        fields = value.get("fields", [])
        if not fields:
            return "types.SimpleNamespace()"
        # `**{...}` accepts field names that are not Python identifiers.
        pairs = [f"{pad}{json.dumps(key)}: {literal(val, depth + 1, helpers)}" for key, val in fields]
        return "types.SimpleNamespace(**{\n" + ",\n".join(pairs) + f"\n{close_pad}}})"
    if tag == "buffer":
        chunks = []
        for byte in value.get("bytes", []):
            if 32 <= byte <= 0x7E and byte not in (ord('"'), ord("\\")):
                chunks.append(chr(byte))
            else:
                chunks.append(f"\\x{byte:02x}")
        return 'b"' + "".join(chunks) + '"'
    if tag == "function":
        behavior = value.get("behavior")
        if behavior == "returnFirst":
            return "(lambda *args, **kwargs: args[0] if args else None)"
        if behavior == "throw":
            helpers["throw"] = True
            return "_afz_stub_throw"
        helpers["capture"] = True
        return "_afz_stub_capture"
    if tag == "stream":
        inner = collection(value.get("items", []), "[", "]", depth, pad, close_pad, helpers)
        if value.get("iterable"):
            return "(item for item in " + inner + ")"
        return f"iter({inner})"
    if tag == "opaque":
        helpers["opaque"].append(value.get("ty", "?"))
        return "None"
    raise ValueError(f"repro.py has no rendering for node tag {tag!r}")


def collection(items, open_, close, depth, pad, close_pad, helpers):
    if not items:
        return open_ + close
    entries = [f"{pad}{literal(item, depth + 1, helpers)}" for item in items]
    return open_ + "\n" + ",\n".join(entries) + f"\n{close_pad}{close}"


def json_to_py(value, depth, helpers):
    """A JSON literal (the `literal` node's payload) as Python source."""
    pad = "    " * (depth + 1)
    close_pad = "    " * depth
    if value is None:
        return "None"
    if isinstance(value, bool):
        return "True" if value else "False"
    if isinstance(value, (int, float)):
        return repr(value)
    if isinstance(value, str):
        return json.dumps(value)
    if isinstance(value, list):
        if not value:
            return "[]"
        entries = [f"{pad}{json_to_py(item, depth + 1, helpers)}" for item in value]
        return "[\n" + ",\n".join(entries) + f"\n{close_pad}]"
    if isinstance(value, dict):
        if not value:
            return "{}"
        entries = [f"{pad}{json.dumps(key)}: {json_to_py(item, depth + 1, helpers)}" for key, item in value.items()]
        return "{\n" + ",\n".join(entries) + f"\n{close_pad}}}"
    raise ValueError(f"repro.py cannot render {value!r}")
